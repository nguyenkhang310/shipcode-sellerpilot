const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const output=path.resolve(__dirname,'../../docs/evaluations/chat-scroll');
fs.mkdirSync(output,{recursive:true});
let browser,page;
(async()=>{
 browser=await chromium.launch({executablePath:process.env.CHROME_EXECUTABLE || undefined,headless:true});
 page=await browser.newPage({viewport:{width:390,height:844}});
 await page.emulateMedia({reducedMotion:'no-preference'});
 const errors=[],checks=[];page.on('pageerror',error=>errors.push(error.message));
 let turn=0;
 await page.route('**/api/v1/chat',async route=>{
  const response=await route.fetch();const body=await response.json();
  body.data.answer=`Câu trả lời dài ${++turn}\n\n`+Array.from({length:65},(_,i)=>`Mục ${i+1}: Ưu tiên kiểm tra số liệu và sản phẩm cần xử lý trong shop.`).join('\n\n');
  await route.fulfill({response,json:body});
 });
 await page.goto(process.env.QA_APP_URL || 'http://127.0.0.1:5174',{waitUntil:'networkidle'});
 await page.getByRole('tab',{name:'SellerPilot',exact:true}).click();
 const input=page.getByRole('textbox',{name:'Nhắn cho SellerPilot'});
 const send=page.getByRole('button',{name:'Gửi tin nhắn',exact:true});
 await input.fill('Phân tích tình hình shop hôm nay');await send.click();
 const typing=page.getByTestId('typing-indicator');await typing.waitFor();
 assert.equal(await typing.locator('[data-testid^="typing-dot-"]').count(),3);
 await page.waitForFunction(()=>Array.from(document.querySelectorAll('[data-testid^="typing-dot-"]')).some(dot=>Number(getComputedStyle(dot).opacity)>.65));
 await page.screenshot({path:path.join(output,'typing.png')});
 await typing.waitFor({state:'detached'});
 const scroll=page.getByTestId('chat-scroll');
 await page.waitForFunction(()=>{const el=document.querySelector('[data-testid="chat-scroll"]');return el.scrollHeight-el.scrollTop-el.clientHeight<12;});
 checks.push('Three-dot typing indicator appears while waiting and disappears after the answer; a long answer scrolls to the bottom');
 await input.fill('Cho mình thêm gợi ý để phát triển shop');await send.click();await typing.waitFor();
 const bounds=await scroll.boundingBox();
 await page.mouse.move(bounds.x+bounds.width/2,bounds.y+80);
 await page.mouse.wheel(0,-1600);
 const latest=page.getByRole('button',{name:'Cuộn đến tin nhắn mới nhất',exact:true});await latest.waitFor();
 await typing.waitFor({state:'detached'});
 const distance=await scroll.evaluate(el=>el.scrollHeight-el.scrollTop-el.clientHeight);
 assert(distance>300,'Reading old messages must not be interrupted by an incoming answer');
 await latest.click();
 await page.waitForFunction(()=>{const el=document.querySelector('[data-testid="chat-scroll"]');return el.scrollHeight-el.scrollTop-el.clientHeight<12;});
 checks.push('Scrolling up while AI thinks preserves reading position; the latest-message button resumes following');
 await input.fill(Array.from({length:18},(_,i)=>'Dòng '+i+' soạn bài đăng nhiều dòng').join('\n'));
 await page.waitForFunction(()=>document.querySelector('textarea').clientHeight>=100);
 const field=await input.boundingBox(), dock=await page.getByTestId('bottom-dock').boundingBox();
 assert(field.height<=129&&field.y+field.height<dock.y);
 await page.waitForFunction(()=>{const el=document.querySelector('[data-testid="chat-scroll"]');return el.scrollHeight-el.scrollTop-el.clientHeight<12;});
 await input.fill('Ngắn');await page.waitForFunction(()=>document.querySelector('textarea').clientHeight<=50);
 checks.push('Growing and shrinking the composer keeps the conversation at the bottom and clear of navigation');
 await page.getByRole('button',{name:'Tạo cuộc trò chuyện mới',exact:true}).click();
 await page.getByRole('button',{name:'Lịch sử trò chuyện',exact:true}).click();
 await page.getByRole('button',{name:/Phân tích tình hình shop hôm nay/}).first().click();
 await page.waitForFunction(()=>{const el=document.querySelector('[data-testid="chat-scroll"]');return el.scrollHeight-el.scrollTop-el.clientHeight<12;});
 checks.push('Opening chat history restores the latest message position');
 assert.deepEqual(errors,[]);
 await page.screenshot({path:path.join(output,'final.png')});
 console.log(JSON.stringify({checks,errors},null,2));
 fs.writeFileSync(path.join(output,'results.json'),JSON.stringify({checks,errors},null,2));
 await browser.close();
})().catch(async error=>{console.error(error);if(page){console.error((await page.locator('body').innerText()).slice(-1800));await page.screenshot({path:path.join(output,'failure.png')});}if(browser)await browser.close();process.exit(1);});
