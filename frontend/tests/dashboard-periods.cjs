// Run against the synthetic API, never a connected seller's database.
const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const output=path.resolve(__dirname,'../../docs/evaluations/dashboard-periods');
fs.mkdirSync(output,{recursive:true});
const delay=ms=>new Promise(resolve=>setTimeout(resolve,ms));
let browser,page;
(async()=>{
 browser=await chromium.launch({executablePath:process.env.CHROME_EXECUTABLE || undefined,headless:true});
 page=await browser.newPage({viewport:{width:390,height:844}});
 const errors=[],requests=[],checks=[],timings={};
 let failDays=0, wrongDays=0;
 const delays={1:30,7:1000,30:180};
 page.on('pageerror',error=>errors.push(error.message));
 await page.route('**/management/dashboard?days=*',async route=>{
  const days=Number(new URL(route.request().url()).searchParams.get('days'));
  requests.push(days);
  const fail=failDays===days, wrong=wrongDays===days;
  const response=await route.fetch();
  const body=await response.json();
  body.data.order_value_vnd=days*1000000;
  if(wrong)body.data.days=days===7?30:7;
  await delay(delays[days]);
  try {
   if(fail)await route.fulfill({status:503,json:{detail:'Kết nối kiểm thử tạm gián đoạn.'}});
   else await route.fulfill({response,json:body});
  }catch(error){if(!/closed|cancel|abort/i.test(error.message))throw error;}
 });
 await page.goto(process.env.QA_APP_URL || 'http://127.0.0.1:5174',{waitUntil:'networkidle'});
 const summary=page.getByTestId('period-summary');
 const ready=days=>page.getByTestId('period-summary').and(page.getByLabel(`Số liệu ${days} ngày`,{exact:true})).waitFor();
 await ready(1);
 const initial=await summary.boundingBox();
 await page.getByRole('button',{name:'7 ngày',exact:true}).click();
 await page.getByText('Đang lấy số liệu từ shop…',{exact:true}).waitFor();
 assert.equal(await summary.getByText('1.000.000',{exact:false}).count(),0,'Never label today metrics as 7-day data');
 const pending=await summary.boundingBox();
 assert(Math.abs(initial.height-pending.height)<=2,JSON.stringify({initial,pending}));
 assert(Math.abs(initial.y-pending.y)<=2,'Period switch must not move the revenue card');
 await page.getByText('UTE MALL · Đã kết nối',{exact:true}).waitFor();
 checks.push('Slow first visit keeps card geometry and shop identity; previous period values are hidden');
 await page.getByRole('button',{name:'30 ngày',exact:true}).click();
 await ready(30);
 assert.match(await summary.innerText(),/30\.000\.000/);
 await page.getByRole('button',{name:'Hôm nay',exact:true}).click();
 await ready(1);
 await delay(1100);
 assert.equal(await summary.getAttribute('aria-label'),'Số liệu 1 ngày');
 assert.match(await summary.innerText(),/1\.000\.000/);
 assert.equal(requests.filter(day=>day===1).length,1);
 checks.push('Rapid 7 → 30 → today ignores the late 7-day response; today uses its cached snapshot');
 let start=performance.now();
 await page.getByRole('button',{name:'30 ngày',exact:true}).click();await ready(30);
 timings.cached_30_days_ms=Math.round(performance.now()-start);
 assert.equal(requests.filter(day=>day===30).length,1);
 assert(timings.cached_30_days_ms<350,'Cached switch should not wait for network');
 await page.getByRole('button',{name:'7 ngày',exact:true}).click();await ready(7);
 start=performance.now();
 for(const label of ['Hôm nay','7 ngày','30 ngày','7 ngày','Hôm nay'])await page.getByRole('button',{name:label,exact:true}).click();
 await ready(1);
 timings.five_cached_switches_ms=Math.round(performance.now()-start);
 const callsBefore=requests.length;
 await page.getByRole('button',{name:'Hôm nay',exact:true}).click();
 await delay(100);assert.equal(requests.length,callsBefore);
 checks.push('All three warmed periods switch without network; tapping the selected period issues no duplicate request');
 // Move the clock forward without waiting a real minute or touching the API.
 const sevensBeforeExpiry=requests.filter(day=>day===7).length;
 await page.evaluate(()=>{const original=Date.now;Date.now=()=>original()+61000;});
 await page.getByRole('button',{name:'7 ngày',exact:true}).click();
 await page.getByText('Đang lấy số liệu từ shop…',{exact:true}).waitFor();await ready(7);
 assert(requests.filter(day=>day===7).length>=sevensBeforeExpiry+1,'Expired period must be fetched; 5-second background reads may add another request');
 checks.push('Snapshots older than 60 seconds are fetched again');
 failDays=7;
 await page.getByRole('tab',{name:'Shop',exact:true}).click();
 await page.getByRole('button',{name:'Đồng bộ dữ liệu',exact:true}).click();
 await page.getByText('Chưa đồng bộ được dữ liệu mới',{exact:true}).waitFor();
 failDays=0;
 await page.getByRole('button',{name:'Đồng bộ dữ liệu',exact:true}).click();
 await page.getByText('Đã kết nối UTE MALL',{exact:true}).waitFor();
 const thirties=requests.filter(day=>day===30).length;
 await page.getByRole('tab',{name:'Quản lý',exact:true}).click();
 await page.getByRole('button',{name:'30 ngày',exact:true}).click();await ready(30);
 assert(requests.filter(day=>day===30).length>=thirties+1);
 checks.push('Manual sync invalidates every period and reports failure honestly; retry recovers');
 // Reject a mismatched server response instead of displaying it in another period.
 await page.evaluate(()=>{const original=Date.now;Date.now=()=>original()+61000;});
 wrongDays=7;
 await page.getByRole('button',{name:'7 ngày',exact:true}).click();
 await page.getByTestId('management-scroll').getByText('Kỳ số liệu trả về không khớp. Vui lòng đồng bộ lại.',{exact:true}).waitFor();
 assert.equal(await summary.getAttribute('aria-label'),'Chưa có số liệu 7 ngày');
 assert.equal(await summary.getByText('30.000.000',{exact:false}).count(),0);
 wrongDays=0;
 await page.getByRole('button',{name:'Thử kết nối lại',exact:true}).click();await ready(7);
 checks.push('Mismatched response is rejected and retry restores the selected period');
 await page.screenshot({path:path.join(output,'final.png')});
 assert.deepEqual(errors,[]);
 const result={checks,timings,requests,errors};
 fs.writeFileSync(path.join(output,'results.json'),JSON.stringify(result,null,2));
 console.log(JSON.stringify(result,null,2));await browser.close();
})().catch(async error=>{console.error(error);if(page){console.error((await page.locator('body').innerText()).slice(0,3000));await page.screenshot({path:path.join(output,'failure.png')});}if(browser)await browser.close();process.exit(1);});
