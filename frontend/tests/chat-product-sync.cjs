// Only run against the isolated chat_reliability_server.py fixture.
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {useQaServer, qaFetch} = require('./qa-server.cjs');
const api = process.env.QA_API_ORIGIN || 'http://127.0.0.1:8123';
const output = path.resolve(__dirname, '../../docs/evaluations/chat-product-sync');
fs.mkdirSync(output, {recursive: true});
let browser, page;
(async () => {
  assert.equal((await (await fetch(api + '/qa/identity')).json()).temporary_shop, true);
  browser = await chromium.launch({executablePath: process.env.CHROME_EXECUTABLE || undefined, headless: true});
  page = await browser.newPage({viewport: {width: 390, height: 844}});
  const errors = [], checks = [];
  page.on('pageerror', error => errors.push(error.message));
  await useQaServer(page);
  await page.goto(process.env.QA_APP_URL || 'http://127.0.0.1:5174', {waitUntil: 'networkidle'});
  const products = page.getByRole('tab', {name: 'Sản phẩm', exact: true});
  const assistant = page.getByRole('tab', {name: 'SellerPilot', exact: true});
  await products.click();
  await page.getByRole('textbox', {name: 'Tìm sản phẩm', exact: true}).filter({visible: true}).waitFor();
  await assistant.click();
  const input = page.getByRole('textbox', {name: 'Nhắn cho SellerPilot'});
  const send = page.getByRole('button', {name: 'Gửi tin nhắn', exact: true});
  async function say(message) {
    await input.fill(message);
    const response = page.waitForResponse(r => r.url().endsWith('/api/v1/chat') && r.request().method() === 'POST');
    await send.click();
    return (await (await response).json()).data;
  }
  async function photo() {
    await page.getByRole('button', {name: 'Thêm ảnh hoặc mở gợi ý'}).click();
    const selected = page.waitForEvent('filechooser');
    await page.getByRole('button', {name: 'Chọn ảnh để đăng sản phẩm'}).click();
    await (await selected).setFiles([path.resolve(__dirname, '../assets/shipcode-logo-app.png')]);
    await page.getByTestId('attachment-strip').waitFor();
    await page.waitForFunction(() => document.querySelector('[aria-label="Gửi tin nhắn"]')?.getAttribute('aria-disabled') !== 'true');
  }
  await photo();
  let result = await say('Tên: Bàn phím đồng bộ; giá: 500k; tồn: 8; ngành hàng: Máy Tính & Laptop; mô tả: Bàn phím gọn nhẹ.');
  const draftId = result.product_draft.id;
  assert.equal(result.product_draft.status, 'ready');
  const publish = page.getByRole('button', {name: 'Đăng sản phẩm lên UTech Official', exact: true});
  await input.fill('Viết lại nội dung bản nháp');
  await send.click();
  await page.getByTestId('typing-indicator').waitFor();
  assert.equal(await publish.isDisabled(), true);
  await page.getByTestId('typing-indicator').waitFor({state: 'detached'});
  checks.push('Publish is disabled while AI rewrites the draft');
  await photo();
  result = await say('Bổ sung ảnh mặt bên cho sản phẩm này, giữ nguyên giá và tồn.');
  assert.equal(result.product_draft.id, draftId);
  assert.equal(result.product_draft.image_count, 2);
  const conversationId = result.conversation_id;
  result = await say('Để sau');
  assert.equal(result.product_draft.status, 'ready');
  assert.equal(result.product_draft.image_count, 2);
  checks.push('Adding photos and postponing keep the same draft, price and stock');
  await page.route('**/api/v1/management/dashboard?**', route => route.fulfill({status: 503,
    json: {detail: {code: 'qa_injected', message: 'Không tải được số liệu.'}}}));
  let published;
  await page.route('**/api/v1/product-drafts/*/publish', async route => {
    const response = await qaFetch(route);
    assert.equal(response.status(), 200);
    published = (await response.json()).data;
    await route.abort('failed');
  });
  await publish.click();
  await page.getByText(/Chưa kết nối được SellerPilot/).filter({visible: true}).waitFor();
  assert.equal(published.status, 'published');
  await page.unroute('**/api/v1/product-drafts/*/publish');
  await products.click();
  const search = page.getByRole('textbox', {name: 'Tìm sản phẩm', exact: true}).filter({visible: true});
  await search.waitFor();
  await page.getByTestId('product-card-' + published.published_product_id).filter({visible: true}).waitFor();
  const fresh = await (await fetch(api + '/api/v1/management/products?sort=newest')).json();
  assert.equal(fresh.data.items[0].id, published.published_product_id);
  checks.push('A warmed Products tab shows the new item after a lost publish reply, even when dashboard refresh fails');
  await assistant.click();
  await publish.click();
  await page.getByText('Đã đăng · UTech Official', {exact: true}).waitFor();
  const found = await (await fetch(api + '/api/v1/management/products?q=' + published.sku)).json();
  assert.equal(found.data.total, 1);
  checks.push('Retrying an uncertain publish confirms the same product without duplicates');
  result = await say('Đổi giá SKU ' + published.sku + ' thành 650k');
  const approved = page.waitForResponse(r => r.url().includes('/proposals/') && r.url().endsWith('/confirm'));
  await page.getByRole('button', {name: 'Xác nhận đổi giá SKU ' + published.sku, exact: true}).click();
  assert.equal((await (await approved).json()).data.status, 'approved');
  await products.click();
  await search.fill(published.sku);
  await page.getByTestId('product-card-' + published.published_product_id).getByText(/650\.000[đ₫]/).waitFor();
  checks.push('A confirmed chat price edit refreshes the product list independently of dashboard errors');
  await assistant.click();
  await page.getByRole('button', {name: 'Tạo cuộc trò chuyện mới', exact: true}).click();
  await page.getByRole('button', {name: 'Lịch sử trò chuyện', exact: true}).click();
  const histories = await (await fetch(api + '/api/v1/conversations')).json();
  const title = histories.data.items.find(row => row.id === conversationId).title;
  await page.getByTestId('history-row-' + conversationId).getByRole('button', {name: title, exact: true}).click();
  const userPhotos = page.getByTestId('user-image-single');
  await userPhotos.first().waitFor();
  assert.equal(await userPhotos.count(), 2);
  checks.push('Reopening history keeps separately uploaded photos under their own captions');
  await page.getByRole('button', {name: 'Tạo cuộc trò chuyện mới', exact: true}).click();
  await page.getByRole('button', {name: 'Thêm ảnh hoặc mở gợi ý'}).click();
  const late = page.waitForEvent('filechooser');
  await page.getByRole('button', {name: 'Chọn ảnh để đăng sản phẩm'}).click();
  const chooser = await late;
  await page.getByRole('button', {name: 'Tạo cuộc trò chuyện mới', exact: true}).click();
  await chooser.setFiles([path.resolve(__dirname, '../assets/shipcode-logo-app.png')]);
  await page.waitForTimeout(250);
  assert.equal(await page.getByTestId('attachment-strip').count(), 0);
  checks.push('A late photo selection cannot leak into a new conversation');
  assert.deepEqual(errors, []);
  await page.screenshot({path: path.join(output, 'final.png')});
  fs.writeFileSync(path.join(output, 'results.json'), JSON.stringify({checks, errors}, null, 2));
  console.log(JSON.stringify({checks, errors}, null, 2));
  await browser.close();
})().catch(async error => {
  console.error(error);
  if (page) { console.error((await page.locator('body').innerText()).slice(-4000)); await page.screenshot({path: path.join(output, 'failure.png')}); }
  if (browser) await browser.close();
  process.exit(1);
});
