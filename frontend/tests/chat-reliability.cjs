const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const APP_URL=process.env.QA_APP_URL || 'http://127.0.0.1:5174';
const API_ORIGIN=process.env.QA_API_ORIGIN || 'http://127.0.0.1:8123';
const OUTPUT=path.resolve(__dirname,'../../docs/evaluations/chat-reliability');
fs.mkdirSync(OUTPUT,{recursive:true});
let browser,page;
(async()=>{
 browser=await chromium.launch({executablePath:process.env.CHROME_EXECUTABLE || undefined,headless:true});
 page=await browser.newPage({viewport:{width:390,height:844}});
 const errors=[],checks=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(APP_URL,{waitUntil:'networkidle'});
 await page.getByRole('tab',{name:'SellerPilot',exact:true}).click();
 const input=page.getByRole('textbox',{name:'Nhắn cho SellerPilot'});
 const send=page.getByRole('button',{name:'Gửi tin nhắn',exact:true});
 await input.fill('Gợi ý chiến lược cho shop lần đầu');
 const sent=page.waitForRequest(r=>r.url().endsWith('/api/v1/chat')&&r.method()==='POST');
 await send.click();const first=(await sent).postDataJSON();
 await page.getByRole('button',{name:'Dừng chờ phản hồi'}).click();
 await page.getByText('Đã dừng phản hồi.',{exact:true}).waitFor();
 let result=await (await fetch(API_ORIGIN+'/api/v1/chat/requests/'+first.request_id)).json();
 assert.equal(result.data.status,'cancelled');checks.push('Stop cancels server task and preserves no completed turn');
 await input.fill('Gợi ý chiến lược sau khi dừng');await send.click();
 await page.getByText('Đã kiểm tra số liệu thử của shop. Bạn có thể tiếp tục trao đổi.',{exact:true}).waitFor();
 checks.push('Conversation can send another message after cancellation');
 let lostId,posts=0;
 await page.route('**/api/v1/chat',async route=>{
   posts++;lostId=route.request().postDataJSON().request_id;
   await route.fetch();await route.abort('failed');
 });
 await input.fill('Kiểm tra tình huống mất phản hồi');await send.click();
 await page.getByRole('button',{name:/Thử lại/}).waitFor();
 await page.unroute('**/api/v1/chat');
 await page.getByRole('button',{name:/Thử lại/}).click();
 await page.getByRole('button',{name:'Dừng chờ phản hồi'}).waitFor({state:'detached'});
 assert.equal(posts,1);
 assert.equal((await page.getByText('Đã kiểm tra số liệu thử của shop. Bạn có thể tiếp tục trao đổi.',{exact:true}).count()),2);
 result=await (await fetch(API_ORIGIN+'/api/v1/chat/requests/'+lostId)).json();
 assert.equal(result.data.status,'completed');checks.push('Lost POST response recovers cached result without another inference');
 await input.fill('Khôi phục yêu cầu sau khi tải lại');
 const pending=page.waitForRequest(r=>r.url().endsWith('/api/v1/chat')&&r.method()==='POST');
 await send.click();const original=(await pending).postDataJSON();
 await page.reload({waitUntil:'networkidle'});
 await page.getByRole('tab',{name:'SellerPilot',exact:true}).click();
 await page.getByRole('textbox',{name:'Nhắn cho SellerPilot'}).waitFor();
 await page.getByText('Khôi phục yêu cầu sau khi tải lại',{exact:true}).filter({visible:true}).waitFor();
 await page.getByRole('button',{name:'Dừng chờ phản hồi'}).waitFor({state:'detached'});
 result=await (await fetch(API_ORIGIN+'/api/v1/conversations/'+original.conversation_id)).json();
 assert.equal(result.data.turns.filter(t=>t.message==='Khôi phục yêu cầu sau khi tải lại').length,1);
 assert.equal(await page.getByText('Khôi phục yêu cầu sau khi tải lại',{exact:true}).filter({visible:true}).count(),1);
 checks.push('Reload resumes saved request and renders one user message and answer');
 // Upload a gallery, drop the response after it was committed, then recover it.
 await page.getByRole('button',{name:'Tạo cuộc trò chuyện mới'}).click();
 await page.getByRole('button',{name:'Thêm ảnh hoặc mở gợi ý'}).click();
 const chooserPromise=page.waitForEvent('filechooser');
 await page.getByRole('button',{name:'Chọn ảnh để đăng sản phẩm'}).click();
 const chooser=await chooserPromise;
 await chooser.setFiles([path.resolve(__dirname,'../assets/shipcode-logo-app.png')]);
 await page.getByTestId('attachment-strip').waitFor();
 await input.fill('Tự viết nội dung cho sản phẩm này');
 let uploadId;
 await page.route('**/api/v1/product-drafts/images-data',async route=>{
   uploadId=route.request().postDataJSON().request_id;
   await route.fetch();await route.abort('failed');
 });
 await send.click();await page.getByRole('button',{name:/Thử lại/}).waitFor();
 await page.unroute('**/api/v1/product-drafts/images-data');
 await page.getByRole('button',{name:/Thử lại/}).click();
 await page.getByText(/Mình đã soạn tiêu đề và mô tả/).waitFor();
 result=await (await fetch(API_ORIGIN+'/api/v1/chat/requests/'+uploadId)).json();
 assert.equal(result.data.status,'completed');
 const convo=await (await fetch(API_ORIGIN+'/api/v1/conversations/'+result.data.conversation_id)).json();
 assert.equal(convo.data.turns.filter(t=>t.response.tool==='create_product_draft').length,1);
 checks.push('Lost gallery response recovers one draft and continues AI copy generation');
 assert.deepEqual(errors,[]);
 await page.screenshot({path:path.join(OUTPUT,'final.png')});
 fs.writeFileSync(path.join(OUTPUT,'results.json'),JSON.stringify({checks,errors},null,2));
 console.log(JSON.stringify({checks,errors},null,2));await browser.close();
})().catch(async e=>{console.error(e); if(page) { console.error((await page.locator('body').innerText()).slice(-6500)); await page.screenshot({path:path.join(OUTPUT,'failure.png')}); } if(browser) await browser.close(); process.exit(1)});
