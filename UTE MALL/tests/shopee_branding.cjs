// Run only against a QA store; login/signup/reply modify the isolated QA DB.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.STORE_URL || 'http://127.0.0.1:5012';
const password = process.env.QA_SELLER_PASSWORD;
if (!password) throw Error('Set QA_SELLER_PASSWORD for the isolated QA store');
const output = path.resolve(__dirname, '../../docs/evaluations/shopee-branding');
fs.mkdirSync(output, { recursive: true });
let browser, page;
(async () => {
  browser = await chromium.launch({ executablePath: process.env.CHROME_EXECUTABLE || undefined, headless: true });
  page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [], checks = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(base + '/login', { waitUntil: 'networkidle' });
  assert.equal(await page.locator('.market-header').count(), 0);
  assert.equal(await page.locator('.auth-header').count(), 1);
  assert.doesNotMatch(await page.locator('body').innerText(), /UTE MALL|demo|mô phỏng/i);
  const logo = page.locator('.auth-heading img');
  await logo.evaluate(img => img.decode());
  const box = await logo.boundingBox(); assert(box.width / box.height > 3);
  assert.equal(await page.locator('.auth-footer-grid>section').count(), 5);
  const submit = page.getByRole('button', { name: 'ĐĂNG NHẬP', exact: true });
  assert.equal(await submit.isDisabled(), true);
  const login = page.getByRole('textbox', { name: 'Email hoặc tên đăng nhập', exact: true });
  const field = page.locator('[name=password]');
  await field.fill('Only-for-visibility-check');
  await page.getByRole('button', { name: 'Hiện mật khẩu', exact: true }).click();
  assert.equal(await field.getAttribute('type'), 'text');
  await page.getByRole('button', { name: 'Ẩn mật khẩu', exact: true }).click();
  assert.equal(await field.getAttribute('type'), 'password'); await field.fill('');
  await page.screenshot({ path: path.join(output, 'login-desktop.png'), fullPage: true });
  checks.push('Shopee vector header, stacked white logo, orange stage, separate auth card and five-column footer');
  for (const method of ['Google', 'Facebook']) {
    await page.getByRole('button', { name: method, exact: true }).click();
    await page.getByRole('dialog').waitFor();
    assert.match(await page.getByRole('dialog').innerText(), /chưa được kết nối/);
    await page.getByRole('button', { name: 'Đăng nhập bằng tài khoản', exact: true }).click();
  }
  await page.getByRole('button', { name: 'Đăng nhập với mã QR', exact: true }).click();
  await page.getByRole('dialog').waitFor(); await page.keyboard.press('Escape');
  for (const width of [320, 390, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Login overflow at ' + width);
    await page.screenshot({ path: path.join(output, `login-${width}.png`), fullPage: true });
  }
  checks.push('Password visibility, empty-submit guard, provider/QR feedback and 320/390/768/1440px layout');
  await login.fill('utech'); await field.fill('Wrong-test-only-password'); await submit.click();
  await page.locator('.auth-alert').waitFor();
  assert.match(await page.locator('.auth-alert').innerText(), /không đúng/);
  await login.fill('utech'); await field.fill(password); await submit.click();
  await page.waitForURL(/\/seller\/?$/);
  await page.locator('.seller-brand img').evaluate(img => img.decode());
  assert.doesNotMatch(await page.locator('body').innerText(), /UTE MALL/);
  await page.screenshot({ path: path.join(output, 'seller-desktop.png'), fullPage: true });
  await page.goto(base + '/seller/reviews');
  const first = page.locator('.review-item').first(); await first.waitFor();
  await first.locator('textarea[name=reply]').fill('Shop cảm ơn phản hồi của bạn.');
  await first.locator('.reply-form button').click();
  await page.getByText('Đã gửi phản hồi, hiển thị trên trang sản phẩm.', { exact: true }).waitFor();
  checks.push('Local account login, inline invalid-password error, seller identity and review reply');
  await page.goto(base + '/');
  await page.locator('.market-logo img').evaluate(img => img.decode());
  assert.equal(await page.getByText('Chưa có đánh giá', { exact: true }).count(), 0);
  await page.screenshot({ path: path.join(output, 'home-desktop.png'), fullPage: false });
  const productUrl = await page.locator('.mall-product-card>a').first().getAttribute('href');
  await page.goto(base + productUrl);
  assert(await page.locator('.review-card').count() > 0);
  await page.locator('#reviews').scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(output, 'reviews-desktop.png') });
  const fourStars = page.locator('.review-filters a').filter({ hasText: /^4 Sao/ });
  await fourStars.click();
  assert.match(await page.locator('.review-filters [aria-current=page]').innerText(), /^4 Sao/);
  assert(await page.locator('.review-card').count() > 0);
  assert.equal(await page.locator('.review-card').first().locator('.review-stars .material-symbols-outlined').count(), 5);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#reviews').scrollIntoViewIfNeeded();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: path.join(output, 'reviews-mobile.png') });
  checks.push('Home card ratings, stored comments, star filters, product review pagination and mobile review layout');
  assert.deepEqual(errors, []);
  fs.writeFileSync(path.join(output, 'results.json'), JSON.stringify({ checks, errors }, null, 2));
  console.log(JSON.stringify({ checks, errors }, null, 2));
  await browser.close();
})().catch(async error => {
  console.error(error);
  if (page) await page.screenshot({ path: path.join(output, 'failure.png') });
  if (browser) await browser.close(); process.exit(1);
});
